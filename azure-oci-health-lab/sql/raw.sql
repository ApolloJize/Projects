CREATE TABLE HEALTH_EVENTS (
  ROW_ID NUMBER(19) PRIMARY KEY,
  EVENT_ID VARCHAR2(32) NOT NULL,
  REVISION NUMBER(10) NOT NULL,
  FACILITY_ID VARCHAR2(16) NOT NULL,
  SERVICE_DATE VARCHAR2(32) NOT NULL,
  SERVICE_TYPE VARCHAR2(32) NOT NULL,
  VISITS VARCHAR2(16) NOT NULL,
  IS_DELETED CHAR(1) NOT NULL,
  UPDATED_AT VARCHAR2(32) NOT NULL
)
/
