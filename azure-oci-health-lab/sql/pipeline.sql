CREATE TABLE FACILITIES (
  FACILITY_ID VARCHAR2(16) PRIMARY KEY,
  FACILITY_NAME VARCHAR2(100) NOT NULL,
  WARD NUMBER(1) CHECK (WARD BETWEEN 1 AND 8)
)
/
CREATE TABLE CURATED_EVENTS (
  EVENT_ID VARCHAR2(32) PRIMARY KEY,
  REVISION NUMBER(10) NOT NULL,
  FACILITY_ID VARCHAR2(16) NOT NULL REFERENCES FACILITIES(FACILITY_ID),
  WARD NUMBER(1) NOT NULL,
  SERVICE_DATE DATE NOT NULL,
  SERVICE_TYPE VARCHAR2(32) NOT NULL,
  VISITS NUMBER(6) NOT NULL
)
/
CREATE TABLE REJECTS (
  EVENT_ID VARCHAR2(32) PRIMARY KEY,
  ROW_ID NUMBER(19) NOT NULL,
  REASON VARCHAR2(32) NOT NULL
)
/
CREATE TABLE PIPELINE_LOCK (ID NUMBER PRIMARY KEY)
/
MERGE INTO PIPELINE_LOCK t USING (SELECT 1 ID FROM DUAL) s ON (t.ID = s.ID)
WHEN NOT MATCHED THEN INSERT (ID) VALUES (s.ID)
/
CREATE TABLE PIPELINE_RUNS (
  RUN_ID VARCHAR2(64) PRIMARY KEY,
  COMPLETED_AT TIMESTAMP WITH TIME ZONE DEFAULT SYSTIMESTAMP,
  ACCEPTED_COUNT NUMBER NOT NULL,
  REJECTED_COUNT NUMBER NOT NULL,
  DELETED_COUNT NUMBER NOT NULL
)
/
CREATE OR REPLACE VIEW CANDIDATES AS
WITH ranked AS (
  SELECT e.*, ROW_NUMBER() OVER (PARTITION BY EVENT_ID ORDER BY REVISION DESC, ROW_ID DESC) rn
  FROM RAW_APP.HEALTH_EVENTS e
), normalized AS (
  SELECT e.ROW_ID, e.EVENT_ID, e.REVISION, UPPER(TRIM(e.FACILITY_ID)) FACILITY_ID,
         f.WARD, UPPER(TRIM(e.SERVICE_TYPE)) SERVICE_TYPE,
         TRIM(e.VISITS) VISITS_TEXT, TRIM(e.SERVICE_DATE) DATE_TEXT,
         UPPER(TRIM(e.IS_DELETED)) IS_DELETED,
         TO_DATE(TRIM(e.SERVICE_DATE) DEFAULT NULL ON CONVERSION ERROR, 'FXYYYY-MM-DD') SERVICE_DATE,
         TO_NUMBER(TRIM(e.VISITS) DEFAULT NULL ON CONVERSION ERROR) VISITS
  FROM ranked e LEFT JOIN FACILITIES f ON f.FACILITY_ID = UPPER(TRIM(e.FACILITY_ID))
  WHERE e.rn = 1
)
SELECT n.*, CASE
  WHEN WARD IS NULL THEN 'unknown_facility'
  WHEN SERVICE_TYPE NOT IN ('SCREENING','IMMUNIZATION','OUTREACH') OR SERVICE_TYPE IS NULL THEN 'invalid_service'
  WHEN NOT REGEXP_LIKE(VISITS_TEXT, '^[0-9]{1,6}$') OR VISITS_TEXT IS NULL THEN 'invalid_visits'
  WHEN SERVICE_DATE IS NULL OR NOT REGEXP_LIKE(DATE_TEXT, '^[0-9]{4}-[0-9]{2}-[0-9]{2}$') THEN 'invalid_date'
  END REASON
FROM normalized n
/
CREATE OR REPLACE PACKAGE CLEAN_INGEST AUTHID DEFINER AS
  PROCEDURE PROMOTE(P_RUN_ID IN VARCHAR2, P_ACCEPTED OUT NUMBER,
                    P_REJECTED OUT NUMBER, P_DELETED OUT NUMBER);
END CLEAN_INGEST;
/
CREATE OR REPLACE PACKAGE BODY CLEAN_INGEST AS
  PROCEDURE PROMOTE(P_RUN_ID IN VARCHAR2, P_ACCEPTED OUT NUMBER,
                    P_REJECTED OUT NUMBER, P_DELETED OUT NUMBER) IS
    lock_id NUMBER;
  BEGIN
    IF P_RUN_ID IS NULL OR LENGTH(P_RUN_ID) > 64 THEN
      RAISE_APPLICATION_ERROR(-20001, 'run_id must contain 1 to 64 characters');
    END IF;
    SELECT ID INTO lock_id FROM PIPELINE_LOCK WHERE ID = 1 FOR UPDATE NOWAIT;
    BEGIN
      SELECT ACCEPTED_COUNT, REJECTED_COUNT, DELETED_COUNT
      INTO P_ACCEPTED, P_REJECTED, P_DELETED FROM PIPELINE_RUNS WHERE RUN_ID = P_RUN_ID;
      COMMIT;
      RETURN;
    EXCEPTION WHEN NO_DATA_FOUND THEN NULL;
    END;
    P_ACCEPTED := 0; P_REJECTED := 0; P_DELETED := 0;
    DELETE FROM CURATED_EVENTS;
    DELETE FROM REJECTS;
    -- One cursor gives one consistent source snapshot; readers see the old
    -- curated snapshot until this entire transaction commits.
    FOR r IN (SELECT * FROM CANDIDATES) LOOP
      IF r.IS_DELETED = 'Y' THEN
        P_DELETED := P_DELETED + 1;
      ELSIF r.REASON IS NOT NULL THEN
        INSERT INTO REJECTS VALUES (r.EVENT_ID, r.ROW_ID, r.REASON);
        P_REJECTED := P_REJECTED + 1;
      ELSE
        INSERT INTO CURATED_EVENTS VALUES (r.EVENT_ID, r.REVISION, r.FACILITY_ID,
          r.WARD, r.SERVICE_DATE, r.SERVICE_TYPE, r.VISITS);
        P_ACCEPTED := P_ACCEPTED + 1;
      END IF;
    END LOOP;
    INSERT INTO PIPELINE_RUNS (RUN_ID, ACCEPTED_COUNT, REJECTED_COUNT, DELETED_COUNT)
      VALUES (P_RUN_ID, P_ACCEPTED, P_REJECTED, P_DELETED);
    COMMIT;
  EXCEPTION WHEN OTHERS THEN
    ROLLBACK;
    RAISE;
  END PROMOTE;
END CLEAN_INGEST;
/
CREATE OR REPLACE VIEW WARD_SUMMARY AS
SELECT WARD, SERVICE_TYPE, SUM(VISITS) VISITS, COUNT(*) EVENT_COUNT
FROM CURATED_EVENTS GROUP BY WARD, SERVICE_TYPE
/
